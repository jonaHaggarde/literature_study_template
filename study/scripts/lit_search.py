#!/usr/bin/env python3
"""
The search half of the search-and-select engine (design: study/search-engine-design.md).

A round is one file pair in study/searches/: round-NN.json (the record, the source) and
round-NN.md (the view the user reads, regenerated by `table`). The script does the mechanical
parts and no judgment: Claude writes the queries and chooses what to propose, this script
runs them against OpenAlex, removes what the study already holds, logs everything, and draws
the approval table. A paper enters a round only if the API returned it, so nothing is proposed
from memory.

Usage (from study/):
    python scripts/lit_search.py new --item "scope item or gap this round serves"
    python scripts/lit_search.py angles --round 1 "plain words: the problem as a layperson says it" ...
    python scripts/lit_search.py search --round 1 --angle plain --query "..." [--reviews] [--from-year 2015]
    python scripts/lit_search.py seed --round 1 --work W123 --direction references|cited-by
    python scripts/lit_search.py pick --round 1 --id W123 --reason "..." --covers "..." [--slot unfamiliar]
    python scripts/lit_search.py table --round 1        # writes round-01.md and prints the table
    python scripts/lit_search.py approve --round 1 1,2,3,6   # the user's numbers -> rows in leads.md
    python scripts/lit_search.py vocab --round 1        # terms in this round's papers not yet searched

Set OPENALEX_MAILTO to an address to use OpenAlex's polite pool (faster, steadier).
"""

