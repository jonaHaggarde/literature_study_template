STUDY = Path(__file__).resolve().parent.parent
SEARCHES = STUDY / "searches"
CATALOG = STUDY / "catalog.md"
LEADS = STUDY / "leads.md"

API = "https://api.openalex.org/works"
SELECT = ("id,doi,title,publication_year,type,language,cited_by_count,primary_location,"
          "best_oa_location,locations,open_access,abstract_inverted_index,topics,"
          "referenced_works,authorships")
PER_PAGE = 25
ROUND_SIZE = 15            # the table's usual ceiling (a warning, not a stop)
SIMILAR = 0.8              # word overlap at which a new query is flagged as a reword

