# ---- small helpers ----------------------------------------------------------------------------

def norm_title(text):
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9]+", " ", (text or "").lower())).strip()


def norm_doi(doi):
    doi = (doi or "").strip().lower()
    return re.sub(r"^(https?://)?(dx\.)?doi\.org/", "", doi)


def short_id(openalex_id):
    return (openalex_id or "").rsplit("/", 1)[-1]


def words(text):
    return {w for w in re.findall(r"[a-z0-9]+", (text or "").lower()) if w not in STOP}


def similarity(a, b):
    wa, wb = words(a), words(b)
    return len(wa & wb) / len(wa | wb) if wa | wb else 0.0


def abstract_text(inverted):
    """OpenAlex ships abstracts as {word: [positions]}; put them back in order."""
    if not inverted:
        return ""
    slots = {}
    for word, positions in inverted.items():
        for p in positions:
            slots[p] = word
    return " ".join(slots[i] for i in sorted(slots))


def read_text(path):
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.exists() else ""


def write_text(path, text, like=None):
    """Write with the line endings the file had (or `like` has), so diffs stay small."""
    crlf = False
    ref = like or path
    if ref.exists():
        crlf = b"\r\n" in ref.read_bytes()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


# ---- OpenAlex ---------------------------------------------------------------------------------

FETCH = None   # tests replace this: a function from a URL to a parsed JSON dict


def _http(url):
    req = urllib.request.Request(url, headers={"User-Agent": "literature-study-template"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as err:
            if err.code in (429, 500, 502, 503) and attempt < 3:
                time.sleep(2 ** attempt)
                continue
            raise SystemExit(f"OpenAlex answered HTTP {err.code} for {url[:120]}")
        except urllib.error.URLError as err:
            raise SystemExit(f"Could not reach OpenAlex: {err.reason}")


def get_json(url):
    return (FETCH or _http)(url)


def api_url(path="", **params):
    mailto = os.environ.get("OPENALEX_MAILTO")
    if mailto:
        params["mailto"] = mailto
    query = urllib.parse.urlencode({k: v for k, v in params.items() if v not in (None, "")},
                                   safe=":,|")
    return f"{API}{path}?{query}" if query else f"{API}{path}"


def candidate(work):
    """The fields the table and the checks need, from one OpenAlex work."""
    primary = work.get("primary_location") or {}
    source = primary.get("source") or {}
    copies = []
    for loc in [work.get("best_oa_location")] + list(work.get("locations") or []):
        if loc and loc.get("pdf_url") and loc["pdf_url"] not in [c["pdf"] for c in copies]:
            host = (loc.get("source") or {}).get("display_name") or ""
            copies.append({"pdf": loc["pdf_url"], "where": host, "version": loc.get("version") or ""})
    oa = (work.get("open_access") or {})
    if copies:
        access = "open copy found"
    elif oa.get("is_oa"):
        access = "unknown"            # open, but only a landing page: the fetch step decides
    else:
        access = "paywalled (you fetch)"
    authors = work.get("authorships") or []
    first = ((authors[0].get("author") or {}).get("display_name") or "") if authors else ""
    return {
        "id": short_id(work.get("id")),
        "doi": norm_doi(work.get("doi")),
        "title": (work.get("title") or "").strip(),
        "first_author": first,
        "year": work.get("publication_year"),
        "venue": source.get("display_name") or "",
        "type": work.get("type") or "",
        "language": work.get("language") or "",
        "cited": work.get("cited_by_count") or 0,
        "access": access,
        "copies": copies,
        "landing": primary.get("landing_page_url") or "",
        "abstract": abstract_text(work.get("abstract_inverted_index")),
        "topics": [t.get("display_name") for t in work.get("topics") or [] if t.get("display_name")],
        "references": [short_id(r) for r in work.get("referenced_works") or []],
        "found_via": [],
    }


def run_search(query, filters, limit):
    url = api_url(search=query, filter=",".join(filters), **{"per-page": limit}, select=SELECT)
    return [candidate(w) for w in get_json(url).get("results", [])]


# ---- what the study already holds -------------------------------------------------------------

DOI_RE = re.compile(r"10\.\d{4,9}/[^\s|)>\]]+", re.I)


def held():
    """(dois, titles) of everything in the catalog and in leads.md, normalised."""
    dois, titles = set(), set()
    for line in read_text(CATALOG).splitlines():
        if line.startswith("title:"):
            titles.add(norm_title(line[6:]))
    in_table = False
    for line in read_text(LEADS).splitlines():
        if line.startswith("| Lead |"):
            in_table = True
            continue
        if in_table and line.startswith("|") and not line.startswith("|---"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and cells[0]:
                titles.add(norm_title(cells[0]))
            dois.update(norm_doi(d.rstrip(".,;")) for d in DOI_RE.findall(line))
    titles.discard("")
    return dois, titles


def is_held(cand, dois, titles):
    return (cand["doi"] and cand["doi"] in dois) or norm_title(cand["title"]) in titles


# ---- rounds -----------------------------------------------------------------------------------

def round_path(n):
    return SEARCHES / f"round-{n:02d}.json"


def round_numbers():
    return sorted(int(m.group(1)) for p in SEARCHES.glob("round-*.json")
                  if (m := re.match(r"round-(\d+)\.json", p.name)))


def load_round(n):
    path = round_path(n)
    if not path.exists():
        raise SystemExit(f"No round {n}. Start one with: lit_search.py new --item \"...\"")
    return json.loads(path.read_text(encoding="utf-8"))


def save_round(rnd):
    SEARCHES.mkdir(parents=True, exist_ok=True)
    round_path(rnd["round"]).write_text(json.dumps(rnd, indent=1, ensure_ascii=False) + "\n",
                                        encoding="utf-8")


def pick_round(arg):
    nums = round_numbers()
    if arg is not None:
        return arg
    if not nums:
        raise SystemExit("No rounds yet. Start one with: lit_search.py new --item \"...\"")
    return nums[-1]


def new_round(item):
    n = (round_numbers() or [0])[-1] + 1
    rnd = {"round": n, "item": item, "created": date.today().isoformat(), "angles": [],
           "queries": [], "candidates": {}, "picks": [], "approved": []}
    save_round(rnd)
    return rnd


def declare_angles(rnd, specs):
    names = {a["name"] for a in rnd["angles"]}
    for spec in specs:
        name, _, note = spec.partition(":")
        name = name.strip()
        if not name or name in names:
            continue
        rnd["angles"].append({"name": name, "note": note.strip()})
        names.add(name)


def earlier_picks(n):
    """IDs already proposed in an earlier round: never proposed twice."""
    ids = set()
    for k in round_numbers():
        if k < n:
            ids.update(p["id"] for p in load_round(k)["picks"])
    return ids


def add_candidates(rnd, found, via):
    """Merge candidates into the round; returns (new, already_held, already_proposed)."""
    dois, titles = held()
    proposed = earlier_picks(rnd["round"])
    new = 0
    n_held = n_proposed = 0
    for cand in found:
        if not cand["id"] or not cand["title"]:
            continue
        if is_held(cand, dois, titles):
            n_held += 1
            continue
        if cand["id"] in proposed:
            n_proposed += 1
            continue
        existing = rnd["candidates"].get(cand["id"])
        if existing is None:
            cand["found_via"] = [via]
            rnd["candidates"][cand["id"]] = cand
            new += 1
        elif via not in existing["found_via"]:
            existing["found_via"].append(via)
    return new, n_held, n_proposed


def flag_rewording(rnd, query):
    """Earlier queries (any round) that are near-duplicates of this one."""
    flags = []
    for k in round_numbers():
        other = rnd if k == rnd["round"] else load_round(k)
        for q in other["queries"]:
            if q["query"] != query and similarity(q["query"], query) >= SIMILAR:
                flags.append(q)
    return flags


def search_round(rnd, angle, query, reviews, from_year, limit):
    if angle not in {a["name"] for a in rnd["angles"]}:
        raise SystemExit(f"Angle '{angle}' is not declared for round {rnd['round']}. Declare the "
                         "angles first (lit_search.py angles), before the first query: that is "
                         "what keeps the search from being written from its own results.")
    base = [f"from_publication_date:{from_year}-01-01"] if from_year else []
    runs = [base + ["type:review"],
            base + ["title_and_abstract.search:survey|review|overview"]] if reviews else [base]
    found = []
    for filters in runs:
        found.extend(run_search(query, filters, limit))
    unique = list({c["id"]: c for c in found}.values())
    flags = flag_rewording(rnd, query)
    new, n_held, n_proposed = add_candidates(rnd, unique, {"kind": "query", "angle": angle})
    rnd["queries"].append({"angle": angle, "query": query, "reviews": reviews,
                           "from_year": from_year, "returned": len(unique), "new": new,
                           "held": n_held, "proposed_before": n_proposed,
                           "at": date.today().isoformat()})
    return unique, new, n_held, n_proposed, flags


def seed_round(rnd, work, direction, limit):
    ref = work if re.fullmatch(r"W\d+", work) else f"https://doi.org/{norm_doi(work)}"
    seed = get_json(api_url(f"/{ref}", select="id,title,referenced_works"))
    sid = short_id(seed.get("id"))
    if direction == "references":
        ids = [short_id(r) for r in (seed.get("referenced_works") or [])][:50]
        found = ([candidate(w) for w in get_json(api_url(
            filter="openalex:" + "|".join(ids), select=SELECT, **{"per-page": 50})).get("results", [])]
            if ids else [])
        via = {"kind": "references-of", "seed": sid}
    else:
        found = [candidate(w) for w in get_json(api_url(
            filter=f"cites:{sid}", sort="cited_by_count:desc", select=SELECT,
            **{"per-page": limit})).get("results", [])]
        via = {"kind": "cited-by", "seed": sid}
    new, n_held, n_proposed = add_candidates(rnd, found, via)
    rnd["queries"].append({"angle": f"{via['kind']} {sid}", "query": seed.get("title") or sid,
                           "reviews": False, "from_year": None, "returned": len(found), "new": new,
                           "held": n_held, "proposed_before": n_proposed,
                           "at": date.today().isoformat()})
    return seed, found, new, n_held, n_proposed


def add_pick(rnd, work_id, reason, covers, slot=""):
    if work_id not in rnd["candidates"]:
        raise SystemExit(f"{work_id} is not a candidate of round {rnd['round']}: only papers "
                         "the search returned can be proposed.")
    if any(p["id"] == work_id for p in rnd["picks"]):
        raise SystemExit(f"{work_id} is already picked.")
    rnd["picks"].append({"id": work_id, "reason": reason, "covers": covers, "slot": slot})


# ---- the view ---------------------------------------------------------------------------------

def cell(text):
    return (text or "").replace("|", "/").replace("\n", " ").strip()


def venue_cell(c):
    venue = "thesis" if c["type"] == "dissertation" else (c["venue"] or "unknown")
    if c["language"] and c["language"] != "en":
        venue += f" ({c['language']})"
    return venue


def filename(c):
    surname = (c["first_author"].split() or ["anon"])[-1]
    slug = "-".join(re.findall(r"[a-z0-9]+", c["title"].lower())[:4])
    return re.sub(r"[^A-Za-z0-9._-]", "", f"{surname}{c['year'] or ''}-{slug}") + ".pdf"


def scholar_link(c):
    return "https://scholar.google.com/scholar?q=" + urllib.parse.quote(f'"{c["title"]}"')


def drift(rnd, previous):
    """The two readings from the design: share by citations/references, share from new angles."""
    cands = [rnd["candidates"][p["id"]] for p in rnd["picks"]]
    if not cands:
        return None, None
    seeded = sum(1 for c in cands if all(v["kind"] != "query" for v in c["found_via"]))
    share_seed = seeded / len(cands)
    if previous is None:
        return share_seed, None
    used = {q["angle"] for q in previous["queries"]}
    fresh = sum(1 for c in cands
                if any(v["kind"] == "query" and v["angle"] not in used for v in c["found_via"])
                and all(v["angle"] not in used for v in c["found_via"] if v["kind"] == "query"))
    return share_seed, fresh / len(cands)


def via_text(c):
    parts = []
    for v in c["found_via"]:
        parts.append(v["angle"] if v["kind"] == "query" else f"{v['kind']} {v['seed']}")
    return ", ".join(parts)


def render_round(rnd, previous):
    n = rnd["round"]
    tried = {q["angle"] for q in rnd["queries"]}
    untried = [a["name"] for a in rnd["angles"] if a["name"] not in tried]
    picks = rnd["picks"]
    out = [f"# Round {n:02d}: {rnd['item']}", "",
           f"Started {rnd['created']}. {len(rnd['queries'])} searches, "
           f"{len(rnd['candidates'])} candidates, {len(picks)} proposed.", ""]
    share_seed, share_fresh = drift(rnd, previous)
    out += ["## Reading of this round", ""]
    out.append("- Proposed from references or citations: "
               + ("n/a (nothing proposed)" if share_seed is None else f"{share_seed:.0%}"))
    out.append("- Proposed from angles not used in the previous round: "
               + ("n/a (first round)" if share_fresh is None and previous is None
                  else "n/a (nothing proposed)" if share_fresh is None else f"{share_fresh:.0%}"))
    out.append(f"- Candidates not proposed (off topic or weaker): {len(rnd['candidates']) - len(picks)}")
    out.append("- Angles declared but not yet searched: " + (", ".join(untried) if untried else "none"))
    if len(picks) > ROUND_SIZE:
        out.append(f"- More than {ROUND_SIZE} proposed; the aim is at most {ROUND_SIZE} per round.")
    out += ["", "This is a reading, not a verdict: the engine does not say a topic is covered.", ""]

    out += ["## Proposed", "",
            "| # | Title | Year | Venue | Cited | Access | Covers | Found via |",
            "|---|---|---|---|---|---|---|---|"]
    for i, p in enumerate(picks, 1):
        c = rnd["candidates"][p["id"]]
        flag = f" **[{p['slot']}]**" if p["slot"] else ""
        out.append(f"| {i} | {cell(c['title'])}{flag} | {c['year'] or ''} | {cell(venue_cell(c))} | "
                   f"{c['cited']} | {c['access']} | {cell(p['covers'])} | {cell(via_text(c))} |")
    out += ["", "Why each was proposed:", ""]
    for i, p in enumerate(picks, 1):
        out.append(f"{i}. {p['reason']}")

    manual = [(i, p, rnd["candidates"][p["id"]]) for i, p in enumerate(picks, 1)
              if rnd["candidates"][p["id"]]["access"] != "open copy found"]
    if manual:
        out += ["", "## To fetch by hand", "",
                "No open copy was found for these. Save each PDF into one folder under the "
                "filename shown; a script matches the files back to their leads. If a paper "
                "has no open copy listed, Scholar's \"All versions\" link often finds one.", ""]
        for i, p, c in manual:
            link = f"https://doi.org/{c['doi']}" if c["doi"] else c["landing"]
            out.append(f"- {i}. {cell(venue_cell(c))}: [{link}]({link}), save as `{filename(c)}`, "
                       f"[Scholar]({scholar_link(c)})")

    out += ["", "## Queries run", "",
            "| Angle | Query | Returned | New | Already held |", "|---|---|---|---|---|"]
    for q in rnd["queries"]:
        extra = " (reviews)" if q.get("reviews") else ""
        out.append(f"| {cell(q['angle'])} | {cell(q['query'])}{extra} | {q['returned']} | "
                   f"{q['new']} | {q['held']} |")
    out += ["", "## Angles declared", ""]
    for a in rnd["angles"]:
        out.append(f"- **{a['name']}**" + (f": {a['note']}" if a["note"] else ""))
    return "\n".join(out) + "\n"


def write_view(rnd):
    n = rnd["round"]
    previous = load_round(n - 1) if round_path(n - 1).exists() else None
    text = render_round(rnd, previous)
    (SEARCHES / f"round-{n:02d}.md").write_text(text, encoding="utf-8")
    return text


# ---- from the user's numbers to leads.md ------------------------------------------------------

def parse_numbers(text, size):
    nums = []
    for part in re.split(r"[,\s]+", text.strip()):
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            nums.extend(range(int(a), int(b) + 1))
        else:
            nums.append(int(part))
    bad = [k for k in nums if not 1 <= k <= size]
    if bad:
        raise SystemExit(f"No such number(s) in the table: {bad} (it has {size} rows).")
    return sorted(set(nums))


def approve(rnd, numbers):
    text = read_text(LEADS)
    if "| Lead |" not in text:
        raise SystemExit("leads.md has no table to add to.")
    today = date.today().isoformat()
    rows = []
    for k in numbers:
        p = rnd["picks"][k - 1]
        c = rnd["candidates"][p["id"]]
        if p["id"] in rnd["approved"]:
            continue
        note = f"DOI {c['doi']}" if c["doi"] else f"OpenAlex {c['id']}"
        if c["copies"]:
            note += f"; open copy: {c['copies'][0]['pdf']}"
        rows.append(f"| {cell(c['title'])} | {cell(p['covers'])} | round {rnd['round']}: "
                    f"{cell(via_text(c))} | found | {cell(note)} | {today} |")
        rnd["approved"].append(p["id"])
    if rows:
        write_text(LEADS, text.rstrip("\n") + "\n" + "\n".join(rows) + "\n")
    return rows


# ---- the vocabulary step ----------------------------------------------------------------------

def terms_of(c):
    toks = [w for w in re.findall(r"[a-z][a-z0-9-]+", f"{c['title']} {c['abstract']}".lower())]
    one = {w for w in toks if len(w) >= 4 and w not in STOP}
    two = {f"{a} {b}" for a, b in zip(toks, toks[1:])
           if a not in STOP and b not in STOP and len(a) >= 3 and len(b) >= 3}
    return one | two


def vocabulary(rnd, top=25):
    """Terms in this round's papers that no earlier query contained, with where they came from."""
    searched = " ".join(q["query"].lower() for k in round_numbers() for q in
                        (rnd if k == rnd["round"] else load_round(k))["queries"])
    ids = [p["id"] for p in rnd["picks"]] or list(rnd["candidates"])
    cands = [rnd["candidates"][i] for i in ids]
    counts, topic_counts = {}, {}
    for c in cands:
        for t in terms_of(c):
            if t not in searched:
                counts[t] = counts.get(t, 0) + 1
        for t in set(c["topics"]):
            if t.lower() not in searched:
                topic_counts[t] = topic_counts.get(t, 0) + 1
    ranked = sorted(((n, t) for t, n in counts.items() if n >= 2), reverse=True)[:top]
    topics = sorted(((n, t) for t, n in topic_counts.items()), reverse=True)[:top]
    return ([(t, n, "abstract") for n, t in ranked] + [(t, n, "topic label") for n, t in topics])


# ---- command line -----------------------------------------------------------------------------

def show_candidates(found, rnd):
    for c in found:
        mark = "" if c["id"] in rnd["candidates"] else "  (held or proposed before)"
        print(f"  {c['id']:<12} {c['year'] or '----'}  cited {c['cited']:>5}  {c['type'][:9]:<9}  "
              f"{c['title'][:80]}{mark}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("new")
    p.add_argument("--item", required=True)
    p = sub.add_parser("angles")
    p.add_argument("--round", type=int)
    p.add_argument("specs", nargs="+", help='"name: what this angle looks for"')
    p = sub.add_parser("search")
    p.add_argument("--round", type=int)
    p.add_argument("--angle", required=True)
    p.add_argument("--query", required=True)
    p.add_argument("--reviews", action="store_true", help="survey and review papers only")
    p.add_argument("--from-year", type=int)
    p.add_argument("--limit", type=int, default=PER_PAGE)
    p = sub.add_parser("seed")
    p.add_argument("--round", type=int)
    p.add_argument("--work", required=True, help="OpenAlex id (W123...) or a DOI")
    p.add_argument("--direction", choices=["references", "cited-by"], required=True)
    p.add_argument("--limit", type=int, default=PER_PAGE)
    p = sub.add_parser("pick")
    p.add_argument("--round", type=int)
    p.add_argument("--id", required=True)
    p.add_argument("--reason", required=True)
    p.add_argument("--covers", required=True)
    p.add_argument("--slot", default="", help='e.g. "unfamiliar" for the room kept for those')
    p = sub.add_parser("table")
    p.add_argument("--round", type=int)
    p = sub.add_parser("approve")
    p.add_argument("--round", type=int)
    p.add_argument("numbers", help='the user\'s numbers, e.g. "1,2,3,6" or "1-4"')
    p = sub.add_parser("vocab")
    p.add_argument("--round", type=int)
    args = ap.parse_args(argv)

    if args.cmd == "new":
        rnd = new_round(args.item)
        print(f"Round {rnd['round']} started. Next: declare its angles before any query.")
        return 0

    rnd = load_round(pick_round(args.round))

    if args.cmd == "angles":
        declare_angles(rnd, args.specs)
        save_round(rnd)
        print("Angles: " + ", ".join(a["name"] for a in rnd["angles"]))
    elif args.cmd == "search":
        found, new, n_held, n_prop, flags = search_round(
            rnd, args.angle, args.query, args.reviews, args.from_year, args.limit)
        save_round(rnd)
        print(f"{len(found)} returned, {new} new, {n_held} already held, "
              f"{n_prop} proposed in an earlier round.")
        for q in flags:
            print(f"  note: close to an earlier query ({q['angle']}): \"{q['query']}\"")
        show_candidates(found, rnd)
    elif args.cmd == "seed":
        seed, found, new, n_held, n_prop = seed_round(rnd, args.work, args.direction, args.limit)
        save_round(rnd)
        print(f"{args.direction} of \"{(seed.get('title') or '')[:70]}\": {len(found)} returned, "
              f"{new} new, {n_held} held, {n_prop} proposed before.")
        show_candidates(found, rnd)
    elif args.cmd == "pick":
        add_pick(rnd, args.id, args.reason, args.covers, args.slot)
        save_round(rnd)
        print(f"{len(rnd['picks'])} proposed so far in round {rnd['round']}.")
    elif args.cmd == "table":
        save_round(rnd)
        print(write_view(rnd))
    elif args.cmd == "approve":
        numbers = parse_numbers(args.numbers, len(rnd["picks"]))
        rows = approve(rnd, numbers)
        save_round(rnd)
        write_view(rnd)
        print(f"{len(rows)} lead row(s) added to leads.md as 'found': {numbers}.")
    elif args.cmd == "vocab":
        for term, n, src in vocabulary(rnd):
            print(f"  {term:<40} {n:>3} paper(s)  [{src}]")
    return 0


