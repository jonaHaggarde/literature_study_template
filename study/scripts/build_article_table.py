#!/usr/bin/env python3
"""
Regenerates article/sections/comparison_rows.tex, the body of the review
article's comparison table, from the method cards in study/notes/.

One row per card. The columns are the fields in
ai_instructions/method-card.md, plus the method's name first and a
reference column last. The reference is a \\cite key derived from the
catalog entry (first author's surname + year).

Derived file. Never hand-edit it; validate_repo.py warns when it is stale.
The float, caption and label live in article/sections/comparison_table.tex,
which is hand-written and which \\input's this file.

Usage:
    python scripts/build_article_table.py             # rewrite the table body
    python scripts/build_article_table.py --check     # exit 1 if it is stale
    python scripts/build_article_table.py --bibitems  # print \\bibitem entries
                                                      # for cited keys missing
                                                      # from references.tex
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_catalog_index import is_processed, parse_catalog  # noqa: E402
from method_cards import (  # noqa: E402
    assign_cite_keys, load_fields, parse_cards,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = REPO_ROOT / "catalog.md"
ARTICLE_DIR = REPO_ROOT.parent / "article"
ROWS_PATH = ARTICLE_DIR / "sections" / "comparison_rows.tex"
REFERENCES_PATH = ARTICLE_DIR / "sections" / "references.tex"

HEADER = (
    "% GENERATED by study/scripts/build_article_table.py from the method cards in\n"
    "% study/notes/ (fields defined in study/ai_instructions/method-card.md).\n"
    "% Do not edit: change a card, then rerun the script. The float, caption and label\n"
    "% are in comparison_table.tex.\n"
)

_TEX_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(s):
    return "".join(_TEX_SPECIAL.get(c, c) for c in s)


def collect_rows(entries, fields):
    """[(sort_key, method_name, {field: value}, cite_key)] for every card."""
    keys = assign_cite_keys(entries)
    rows = []
    for order, (entry_id, f) in enumerate(entries):
        if entry_id == "EXAMPLE" or not is_processed(f) or not f.get("note"):
            continue
        note = REPO_ROOT / f["note"]
        if not note.exists():
            continue
        cards = parse_cards(note.read_text(encoding="utf-8"))
        for i, (name, values) in enumerate(cards):
            year = f.get("year", "")
            rows.append(((year, keys[entry_id], order, i), name, values, keys[entry_id]))
    rows.sort(key=lambda r: r[0])
    return rows


def render(entries, fields):
    rows = collect_rows(entries, fields)
    ncols = len(fields) + 2
    spec = "@{}" + "L " * (len(fields) + 1) + "l@{}"
    heads = ["Method"] + [k.replace("_", " ").capitalize() for k in fields] + ["Ref."]
    out = [HEADER.rstrip("\n"), f"\\begin{{tabularx}}{{\\textwidth}}{{{spec}}}", "\\toprule"]
    out.append(" & ".join(f"\\textbf{{{h}}}" for h in heads) + "\\\\")
    out.append("\\midrule")
    if not rows:
        out.append(
            f"\\multicolumn{{{ncols}}}{{@{{}}l@{{}}}}"
            "{\\todo{No method cards yet: see study/ai\\_instructions/method-card.md}}\\\\"
        )
    for _, name, values, key in rows:
        cells = [tex_escape(name)] + [tex_escape(values.get(k, "")) for k in fields]
        cells.append(f"\\cite{{{key}}}")
        out.append(" & ".join(cells) + "\\\\")
    out += ["\\bottomrule", "\\end{tabularx}", ""]
    return "\n".join(out), rows


def bibitem(entry_id, f, key):
    return (
        f"\\bibitem{{{key}}}\n"
        f"{tex_escape(f.get('authors', ''))}.\n"
        f"\\newblock {tex_escape(f.get('title', entry_id))}.\n"
        f"\\newblock {tex_escape(f.get('year', ''))}.\n"
    )


def main():
    args = set(sys.argv[1:])
    if not ARTICLE_DIR.exists():
        print("article/ not found; nothing to build.", file=sys.stderr)
        return 1
    entries = parse_catalog(CATALOG_PATH.read_text(encoding="utf-8"))
    fields = load_fields()
    text, rows = render(entries, fields)

    if "--bibitems" in args:
        have = set()
        if REFERENCES_PATH.exists():
            have = set(re.findall(r"\\bibitem(?:\[[^\]]*\])?\{([^}]*)\}",
                                  REFERENCES_PATH.read_text(encoding="utf-8")))
        keys = assign_cite_keys(entries)
        by_key = {keys[i]: (i, f) for i, f in entries if i in keys}
        missing = sorted({r[3] for r in rows} - have)
        for key in missing:
            print(bibitem(*by_key[key], key))
        print(f"% {len(missing)} missing \\bibitem entr{'y' if len(missing) == 1 else 'ies'}",
              file=sys.stderr)
        return 0

    current = ROWS_PATH.read_text(encoding="utf-8") if ROWS_PATH.exists() else ""
    if "--check" in args:
        return 0 if current == text else 1
    if current != text:
        ROWS_PATH.write_text(text, encoding="utf-8")
        print(f"Wrote {ROWS_PATH.relative_to(REPO_ROOT.parent).as_posix()} ({len(rows)} row(s)).")
    else:
        print("comparison_rows.tex already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
