#!/usr/bin/env python3
"""
Regenerates the two derived files of the review article:

  article/sections/comparison_rows.tex  the body of the comparison table,
      one row per method card in study/notes/. Columns are the fields in
      ai_instructions/method-card.md, with the method's name first and a
      reference last. If any card has a `family`, rows are grouped by it.
  article/sections/references.tex       the whole thebibliography list,
      in order of first citation in the article's source, so the numbers
      follow the repo's citation convention. Catalog-derived keys (first
      author's surname + year) are written from catalog.md; any other key
      is taken from article/sections/references_extra.tex, the hand-written
      home of sources that are not in the catalog.

Derived files. Never hand-edit them; validate_repo.py rebuilds them and
warns when they were stale.

Usage:
    python scripts/build_article_table.py             # rewrite both files
    python scripts/build_article_table.py --check     # exit 1 if either is stale
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_catalog_index import parse_catalog  # noqa: E402
from method_cards import (  # noqa: E402
    FAMILY_KEY, assign_cite_keys, iter_cards, load_families, load_fields,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = REPO_ROOT / "catalog.md"
ARTICLE_DIR = REPO_ROOT.parent / "article"
SECTIONS = ARTICLE_DIR / "sections"
ROWS_PATH = SECTIONS / "comparison_rows.tex"
REFERENCES_PATH = SECTIONS / "references.tex"
EXTRA_PATH = SECTIONS / "references_extra.tex"
MAIN_PATH = ARTICLE_DIR / "main.tex"

COMMENT_RE = re.compile(r"(?<!\\)%.*")
INPUT_RE = re.compile(r"\\input\{([^}]*)\}")
CITE_RE = re.compile(r"\\cite[a-z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}")
BIBITEM_SPLIT_RE = re.compile(r"(?=\\bibitem)")
BIBITEM_KEY_RE = re.compile(r"\\bibitem(?:\[[^\]]*\])?\{([^}]*)\}")

ROWS_HEADER = (
    "% GENERATED by study/scripts/build_article_table.py from the method cards in\n"
    "% study/notes/ (fields defined in study/ai_instructions/method-card.md).\n"
    "% Do not edit: change a card, then rerun the script. The float, caption and label\n"
    "% are in comparison_table.tex.\n"
)
REFS_HEADER = (
    "% GENERATED by study/scripts/build_article_table.py, in order of first citation in the\n"
    "% article. Do not edit: catalog sources come from study/catalog.md, other sources from\n"
    "% references_extra.tex. Rerun the script after adding a citation.\n"
)

_TEX_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(s):
    return "".join(_TEX_SPECIAL.get(c, c) for c in s)


# ---- the table ---------------------------------------------------------------------------

def collect_rows(entries):
    """[(sort_key, family, method_name, values, cite_key)] for every card."""
    rows = []
    for order, (entry_id, f, _note, name, values, key) in enumerate(iter_cards(entries)):
        rows.append(((f.get("year", ""), key, order), values.get(FAMILY_KEY, ""), name, values, key))
    rows.sort(key=lambda r: r[0])
    return rows


def family_title(name):
    return name.replace("-", " ").replace("_", " ").capitalize() if name else "Ungrouped"


def render_rows(entries, fields):
    rows = collect_rows(entries)
    ncols = len(fields) + 2
    spec = "@{}" + "L " * (len(fields) + 1) + "l@{}"
    heads = ["Method"] + [k.replace("_", " ").capitalize() for k in fields] + ["Ref."]
    out = [ROWS_HEADER.rstrip("\n"), f"\\begin{{tabularx}}{{\\textwidth}}{{{spec}}}", "\\toprule"]
    out.append(" & ".join(f"\\textbf{{{h}}}" for h in heads) + "\\\\")
    out.append("\\midrule")
    if not rows:
        out.append(
            f"\\multicolumn{{{ncols}}}{{@{{}}l@{{}}}}"
            "{\\todo{No method cards yet: see study/ai\\_instructions/method-card.md}}\\\\"
        )

    def row_line(name, values, key):
        cells = [tex_escape(name)] + [tex_escape(values.get(k, "")) for k in fields]
        cells.append(f"\\cite{{{key}}}")
        return " & ".join(cells) + "\\\\"

    if any(r[1] for r in rows):
        canonical = load_families()
        present = {r[1] for r in rows}
        order = [f for f in canonical if f in present]
        order += sorted(f for f in present if f and f not in canonical)
        if "" in present:
            order.append("")
        for gi, fam in enumerate(order):
            if gi:
                out.append("\\midrule")
            out.append(f"\\multicolumn{{{ncols}}}{{@{{}}l@{{}}}}{{\\textbf{{{tex_escape(family_title(fam))}}}}}\\\\")
            out.append("\\addlinespace[2pt]")
            out += [row_line(n, v, k) for _, f, n, v, k in rows if f == fam]
    else:
        out += [row_line(n, v, k) for _, _f, n, v, k in rows]
    out += ["\\bottomrule", "\\end{tabularx}", ""]
    return "\n".join(out)


# ---- the references ----------------------------------------------------------------------

def article_text_in_order(path, _depth=0):
    """The article's source with \\input expanded in place and comments
    removed, skipping references.tex (it holds no citations)."""
    text = COMMENT_RE.sub("", path.read_text(encoding="utf-8"))

    def expand(m):
        name = m.group(1)
        target = ARTICLE_DIR / (name if name.endswith(".tex") else name + ".tex")
        if target == REFERENCES_PATH or not target.exists() or _depth > 8:
            return ""
        return article_text_in_order(target, _depth + 1)

    return INPUT_RE.sub(expand, text)


def cited_keys_in_order():
    seen, order = set(), []
    if not MAIN_PATH.exists():
        return order
    for m in CITE_RE.finditer(article_text_in_order(MAIN_PATH)):
        for key in (k.strip() for k in m.group(1).split(",")):
            if key and key not in seen:
                seen.add(key)
                order.append(key)
    return order


def extra_bibitems():
    """{key: raw bibitem block} from references_extra.tex."""
    if not EXTRA_PATH.exists():
        return {}
    text = COMMENT_RE.sub("", EXTRA_PATH.read_text(encoding="utf-8"))
    blocks = {}
    for chunk in BIBITEM_SPLIT_RE.split(text):
        m = BIBITEM_KEY_RE.match(chunk.strip())
        if m:
            blocks[m.group(1)] = chunk.strip() + "\n"
    return blocks


def catalog_bibitem(entry, key):
    entry_id, f = entry
    return (
        f"\\bibitem{{{key}}}\n"
        f"{tex_escape(f.get('authors', ''))}.\n"
        f"\\newblock {tex_escape(f.get('title', entry_id))}.\n"
        f"\\newblock {tex_escape(f.get('year', ''))}.\n"
    )


def render_references(entries):
    keys = assign_cite_keys(entries)
    by_key = {keys[i]: (i, f) for i, f in entries if i in keys}
    extra = extra_bibitems()
    items = []
    for key in cited_keys_in_order():
        if key in by_key:
            items.append(catalog_bibitem(by_key[key], key))
        elif key in extra:
            items.append(extra[key])
        # an unresolvable key is left out; validate_repo.py fails on it
    body = "\n".join(items)
    return REFS_HEADER + "\n\\begin{thebibliography}{99}\n\n" + body + "\n\\end{thebibliography}\n"


# ---- driver ------------------------------------------------------------------------------

def read(path):
    return path.read_text(encoding="utf-8") if path.exists() else ""


def main():
    if not ARTICLE_DIR.exists():
        print("article/ not found; nothing to build.", file=sys.stderr)
        return 1
    entries = parse_catalog(CATALOG_PATH.read_text(encoding="utf-8"))
    rows_text = render_rows(entries, load_fields())
    # references depend on the rows (the table cites), so scan after writing them
    check = "--check" in sys.argv
    stale = rows_text != read(ROWS_PATH)
    if not check and stale:
        ROWS_PATH.write_text(rows_text, encoding="utf-8")
    refs_text = render_references(entries)
    refs_stale = refs_text != read(REFERENCES_PATH)
    if check:
        # --check scans the rows file as it is on disk, so it can only say
        # whether the written pair is consistent with the sources
        return 1 if (stale or refs_stale) else 0
    if refs_stale:
        REFERENCES_PATH.write_text(refs_text, encoding="utf-8")
    n = rows_text.count("\\cite{")
    print(f"comparison_rows.tex: {'rewritten' if stale else 'up to date'} ({n} row(s)); "
          f"references.tex: {'rewritten' if refs_stale else 'up to date'}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
