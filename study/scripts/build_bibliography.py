#!/usr/bin/env python3
"""
Generates each article's own bibliography under articles/<name>/:

  references.bib            a BibTeX file holding exactly the sources that article
                            cites, and nothing else
  sections/references.tex   what the article \\input's at its end: the BibTeX style
                            and database commands, or a comment if it cites nothing

Why one bibliography per article: articles do not cite the same sources, and each
should be self-contained and movable (a specification is written here but
implemented elsewhere). BibTeX with the `unsrt` style prints only what is cited,
numbered in order of first citation, which is the repo's citation convention
(local to each document).

Where an entry comes from: a source in study/catalog.md is written from the catalog
and cited by its derived key (first author's surname + year); any other source is a
hand-written BibTeX entry in articles/common/references_extra.bib (a provided
document, a rulebook). An article with no \\cite gets **no** references.bib and no
bibliography section.

Derived files. Never hand-edit them; validate_repo.py rebuilds them.

Usage:
    python scripts/build_bibliography.py            # rewrite every article's files
    python scripts/build_bibliography.py --check    # exit 1 if any is stale
"""

import re
import sys
from pathlib import Path

import _console  # noqa: F401  (UTF-8 console output on Windows)

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_catalog_index import parse_catalog  # noqa: E402
from method_cards import assign_cite_keys  # noqa: E402
from texutil import tex_escape  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = REPO_ROOT / "catalog.md"
ARTICLES_DIR = REPO_ROOT.parent / "articles"
EXTRA_PATH = ARTICLES_DIR / "common" / "references_extra.bib"
NOT_ARTICLES = {"common", "gates"}

COMMENT_RE = re.compile(r"(?<!\\)%.*")
INPUT_RE = re.compile(r"\\input\{([^}]*)\}")
CITE_RE = re.compile(r"\\cite[a-z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}")
ENTRY_START_RE = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,")

BIB_HEADER = (
    "% GENERATED by study/scripts/build_bibliography.py: exactly the sources this article cites.\n"
    "% Catalog sources are written from study/catalog.md; others come from\n"
    "% articles/common/references_extra.bib. Do not edit; rerun the script.\n\n"
)
REFS_WITH_SOURCES = (
    "% GENERATED by study/scripts/build_bibliography.py. Do not edit.\n"
    "\\bibliographystyle{unsrt}\n"
    "\\bibliography{references}\n"
)
REFS_NONE = (
    "% GENERATED by study/scripts/build_bibliography.py. Do not edit.\n"
    "% This article cites no sources, so it has no bibliography (and no references.bib).\n"
)


# ---- finding articles and what they cite ---------------------------------------------------

def article_dirs(articles_dir=ARTICLES_DIR):
    """Folders under articles/ that hold an article (a main.tex)."""
    if not articles_dir.exists():
        return []
    return [p for p in sorted(articles_dir.iterdir())
            if p.is_dir() and p.name not in NOT_ARTICLES and not p.name.startswith((".", "_"))
            and (p / "main.tex").exists()]


def article_text_in_order(path, article_dir, _depth=0):
    """The article's source with \\input expanded in place and comments removed,
    skipping its generated references.tex (it holds no citations)."""
    text = COMMENT_RE.sub("", path.read_text(encoding="utf-8"))
    skip = article_dir / "sections" / "references.tex"

    def expand(m):
        name = m.group(1)
        target = article_dir / (name if name.endswith(".tex") else name + ".tex")
        if target.resolve() == skip.resolve() or not target.exists() or _depth > 8:
            return ""
        return article_text_in_order(target, article_dir, _depth + 1)

    return INPUT_RE.sub(expand, text)


def cited_keys_in_order(article_dir):
    seen, order = set(), []
    main = article_dir / "main.tex"
    if not main.exists():
        return order
    for m in CITE_RE.finditer(article_text_in_order(main, article_dir)):
        for key in (k.strip() for k in m.group(1).split(",")):
            if key and key not in seen:
                seen.add(key)
                order.append(key)
    return order


# ---- BibTeX entries ------------------------------------------------------------------------

def parse_bib_entries(text):
    """{key: raw entry text} from BibTeX source, matching braces so an entry
    with nested braces is taken whole. Comments and @comment blocks are ignored."""
    entries = {}
    for m in ENTRY_START_RE.finditer(text):
        if m.group(1).lower() in ("comment", "string", "preamble"):
            continue
        depth, i = 0, text.index("{", m.start())
        for j in range(i, len(text)):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    entries[m.group(2)] = text[m.start():j + 1]
                    break
    return entries


def bib_keys(text):
    return set(parse_bib_entries(text))


def bibtex_authors(authors):
    """'First Last, First Last and First Last' -> 'First Last and First Last and ...'."""
    names = [a.strip() for a in re.split(r",| and ", authors or "") if a.strip()]
    return " and ".join(tex_escape(n) for n in names)


def catalog_bib_entry(entry_id, fields, key):
    parts = [f"@misc{{{key},"]
    if fields.get("authors", "").strip():
        parts.append(f"  author = {{{bibtex_authors(fields['authors'])}}},")
    parts.append(f"  title = {{{{{tex_escape(fields.get('title') or entry_id)}}}}},")
    if fields.get("year", "").strip():
        parts.append(f"  year = {{{tex_escape(fields['year'].strip())}}},")
    parts.append("}")
    return "\n".join(parts)


def extra_entries():
    return parse_bib_entries(EXTRA_PATH.read_text(encoding="utf-8")) if EXTRA_PATH.exists() else {}


def build_for_article(article_dir, catalog_entries, extras):
    """(bib_text or None, references_tex, unresolved_keys) for one article."""
    keys = cited_keys_in_order(article_dir)
    if not keys:
        return None, REFS_NONE, []
    ckeys = assign_cite_keys(catalog_entries)
    by_key = {ckeys[i]: (i, f) for i, f in catalog_entries if i in ckeys}
    blocks, unresolved = [], []
    for key in keys:
        if key in by_key:
            blocks.append(catalog_bib_entry(by_key[key][0], by_key[key][1], key))
        elif key in extras:
            blocks.append(extras[key])
        else:
            unresolved.append(key)
    if not blocks:
        return None, REFS_NONE, unresolved
    return BIB_HEADER + "\n\n".join(blocks) + "\n", REFS_WITH_SOURCES, unresolved


# ---- driver ----------------------------------------------------------------------------------

def read(path):
    return path.read_text(encoding="utf-8") if path.exists() else ""


def main():
    check = "--check" in sys.argv
    catalog_entries = parse_catalog(CATALOG_PATH.read_text(encoding="utf-8"))
    extras = extra_entries()
    stale = 0
    for adir in article_dirs():
        bib, refs_tex, unresolved = build_for_article(adir, catalog_entries, extras)
        bib_path, refs_path = adir / "references.bib", adir / "sections" / "references.tex"
        for key in unresolved:
            print(f"WARNING {adir.name}: \\cite{{{key}}} is in neither the catalog nor "
                  "articles/common/references_extra.bib", file=sys.stderr)
        changed = (bib or "") != read(bib_path) or refs_tex != read(refs_path)
        stale += changed
        if check or not changed:
            continue
        refs_path.parent.mkdir(parents=True, exist_ok=True)
        refs_path.write_text(refs_tex, encoding="utf-8")
        if bib is None:
            bib_path.unlink(missing_ok=True)
        else:
            bib_path.write_text(bib, encoding="utf-8")
        print(f"{adir.name}: bibliography rewritten ({'no sources' if bib is None else str(len(bib_keys(bib))) + ' source(s)'}).")
    if check:
        return 1 if stale else 0
    if not stale:
        print("Bibliographies already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
