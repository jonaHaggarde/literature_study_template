#!/usr/bin/env python3
"""
Decision trees: parse the canonical table, check it, and regenerate the
mermaid diagram that follows it.

A decision tree lives in a markdown file under ideation/ as a table between
`<!-- decision-tree -->` and `<!-- /decision-tree -->`. The table is the
source of truth; the diagram right after it is derived (the same discipline as
catalog.md and catalog-index.md) and is never hand-edited.

One row per answer. Columns:

  Q          question id, e.g. Q1 (rows of one question sit together; the
             first question is the root)
  question   the question, as a question (given on at least one of its rows)
  answer     one possible answer to it
  status     chosen    the path continues from this answer
             explored  examined and rejected
             identified  listed, never examined
  then       chosen rows only: the next question id, or END
  method     the alternative this answer would give (rejected rows), or the
             assembled recommendation (the chosen row that says END)
  source     optional pointer to the evidence (a deep-dive section, a note)
  motivation why this answer won or lost; left empty until the team decides
             (each edge is a placeholder for it)

Cells cannot contain `|`. Rules checked: a known status, at most one chosen
answer per question, `then` only on chosen rows and pointing at a real
question, every question reachable from the root, and a method wherever one is
needed. A question with no chosen answer is simply still open.

Usage:
    python scripts/build_decision_trees.py            # rewrite stale diagrams
    python scripts/build_decision_trees.py --check    # exit 1 if any is stale or invalid
"""

import re
import sys
from pathlib import Path

import _console  # noqa: F401  (UTF-8 console output on Windows)

REPO_ROOT = Path(__file__).resolve().parent.parent
IDEATION_DIR = REPO_ROOT.parent / "ideation"

COLUMNS = ["Q", "question", "answer", "status", "then", "method", "source", "motivation"]
STATUSES = ("chosen", "explored", "identified")

TABLE_RE = re.compile(r"(<!--\s*decision-tree\s*-->)(.*?)(<!--\s*/decision-tree\s*-->)", re.S)
DIAGRAM_RE = re.compile(r"\s*<!--\s*decision-tree-diagram[^>]*-->.*?<!--\s*/decision-tree-diagram\s*-->", re.S)
DIAGRAM_NOTE = ("decision-tree-diagram: generated by study/scripts/build_decision_trees.py "
                "from the table above; do not edit")


def parse_table(block):
    """Rows (list of dicts) from the markdown table inside a tree block, and
    a list of problems."""
    rows, problems = [], []
    lines = [ln.strip() for ln in block.strip().splitlines() if ln.strip().startswith("|")]
    if not lines:
        return rows, ["no table found between the decision-tree markers"]
    header = [c.strip() for c in lines[0].strip("|").split("|")]
    if header != COLUMNS:
        return rows, [f"table header must be exactly: {' | '.join(COLUMNS)}  (found: {' | '.join(header)})"]
    for ln in lines[1:]:
        cells = [c.strip() for c in ln.strip("|").split("|")]
        if all(re.fullmatch(r":?-{3,}:?", c) for c in cells if c):
            continue  # the separator row
        if len(cells) != len(COLUMNS):
            problems.append(f"row has {len(cells)} cells, expected {len(COLUMNS)} (a '|' inside a cell?): {ln[:60]}")
            continue
        rows.append(dict(zip(COLUMNS, cells)))
    return rows, problems


def question_order(rows):
    seen = []
    for r in rows:
        if r["Q"] not in seen:
            seen.append(r["Q"])
    return seen


def validate(rows):
    problems = []
    if not rows:
        return ["the table has no rows"]
    order = question_order(rows)
    text = {}
    for r in rows:
        if not r["Q"]:
            problems.append("a row has no Q id")
            continue
        if r["question"]:
            if text.setdefault(r["Q"], r["question"]) != r["question"]:
                problems.append(f"{r['Q']}: two different question texts")
    for q in order:
        if q and q not in text:
            problems.append(f"{q}: no row gives the question text")
    chosen = {}
    for r in rows:
        q, st = r["Q"], r["status"]
        if st not in STATUSES:
            problems.append(f"{q}: status '{st}' must be one of {', '.join(STATUSES)}")
            continue
        if not r["answer"]:
            problems.append(f"{q}: a row has no answer")
        if st == "chosen":
            if q in chosen:
                problems.append(f"{q}: more than one chosen answer")
            chosen[q] = r
            nxt = r["then"]
            if not nxt:
                problems.append(f"{q}: the chosen answer needs a 'then' (a question id or END)")
            elif nxt != "END" and nxt not in order:
                problems.append(f"{q}: 'then' points at '{nxt}', which is not a question in this table")
            if nxt == "END" and not r["method"]:
                problems.append(f"{q}: the chosen answer ends the tree, so 'method' must name the recommendation")
        else:
            if r["then"]:
                problems.append(f"{q}: only a chosen answer has a 'then'")
            if not r["method"]:
                problems.append(f"{q}: a rejected answer must name the method it would give")
    # every question reachable from the root along chosen answers
    reach, cur = set(), order[0]
    while cur and cur != "END" and cur not in reach:
        reach.add(cur)
        cur = chosen.get(cur, {}).get("then", "")
    for q in order:
        if q not in reach:
            problems.append(f"{q}: not reachable from {order[0]} along chosen answers")
    return problems


def stats(rows):
    rejected = [r for r in rows if r["status"] in ("explored", "identified")]
    explored = sum(1 for r in rejected if r["status"] == "explored")
    order = question_order(rows)
    decided = sum(1 for q in order if any(r["Q"] == q and r["status"] == "chosen" for r in rows))
    unwritten = sum(1 for r in rows if r["status"] in ("chosen", "explored") and not r["motivation"])
    return {"questions": len(order), "decided": decided, "alternatives": len(rejected),
            "explored": explored, "motivations_missing": unwritten}


def _label(text):
    """Escape a cell for a quoted mermaid label. Angle brackets would be read
    as HTML tags and swallow the text, so they become entities."""
    return (text.replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")
            .replace("\n", " "))


def render_mermaid(rows):
    order = question_order(rows)
    text = {}
    for r in rows:
        if r["question"]:
            text.setdefault(r["Q"], r["question"])
    chosen = {r["Q"]: r for r in rows if r["status"] == "chosen"}
    out = ["flowchart TD"]
    edges, thick = [], []
    on_path = set()
    cur = order[0]
    while cur and cur != "END" and cur not in on_path and cur in chosen:
        on_path.add(cur)
        cur = chosen[cur]["then"]
    for q in order:
        cls = "path" if q in chosen else "open"
        out.append(f'  {q}["{_label(q + ": " + text.get(q, ""))}"]:::{cls}')
    for q in order:
        n = 0
        for r in (r for r in rows if r["Q"] == q):
            ans = _label(r["answer"])
            if r["status"] == "chosen":
                if r["then"] == "END":
                    out.append(f'  R["{_label("Recommended: " + r["method"])}"]:::recommended')
                    target = "R"
                else:
                    target = r["then"]
                thick.append(len(edges))
                edges.append(f'  {q} ==>|"{ans}"| {target}')
            else:
                n += 1
                leaf = f"L_{q}_{n}"
                note = "explored" if r["status"] == "explored" else "not examined"
                out.append(f'  {leaf}["{_label(r["method"])}<br/>({note})"]:::{r["status"]}')
                edges.append(f'  {q} -->|"{ans}"| {leaf}')
    out += edges
    if thick:
        out.append("  linkStyle " + ",".join(str(i) for i in thick) + " stroke:#0F6E56,stroke-width:3px")
    out += [
        "  classDef path fill:#E1F5EE,stroke:#0F6E56,color:#04342C",
        "  classDef open fill:#FAEEDA,stroke:#854F0B,color:#412402",
        "  classDef recommended fill:#E1F5EE,stroke:#0F6E56,stroke-width:3px,color:#04342C",
        "  classDef explored fill:#F1EFE8,stroke:#5F5E5A,color:#2C2C2A",
        "  classDef identified fill:#FFFFFF,stroke:#888780,color:#444441,stroke-dasharray:4 3",
    ]
    return "\n".join(out)


def process_text(text):
    """Regenerate every tree's diagram in a document. Returns (new_text,
    results) where results is a list of (rows_or_None, problems)."""
    results = []

    def sub(m):
        rows, problems = parse_table(m.group(2))
        if not problems:
            problems = validate(rows)
        results.append((rows if not problems else None, problems))
        table = m.group(1) + m.group(2) + m.group(3)
        if problems:
            return table  # leave the document alone; the problems are reported
        diagram = (f"\n\n<!-- {DIAGRAM_NOTE} -->\n```mermaid\n{render_mermaid(rows)}\n```\n"
                   f"<!-- /decision-tree-diagram -->")
        return table + diagram

    # drop any existing diagram directly after a table, then re-add a fresh one
    cleaned = []
    pos = 0
    for m in TABLE_RE.finditer(text):
        cleaned.append(text[pos:m.end()])
        tail = DIAGRAM_RE.match(text, m.end())
        pos = tail.end() if tail else m.end()
    cleaned.append(text[pos:])
    stripped = "".join(cleaned)
    new_text = TABLE_RE.sub(sub, stripped)
    return new_text, results


def tree_files():
    if not IDEATION_DIR.exists():
        return []
    return [p for p in sorted(IDEATION_DIR.rglob("*.md")) if p.name != "README.md"]


def main():
    check = "--check" in sys.argv
    bad = stale = 0
    for path in tree_files():
        text = path.read_text(encoding="utf-8")
        if "<!-- decision-tree" not in text:
            continue
        new_text, results = process_text(text)
        rel = path.relative_to(IDEATION_DIR.parent).as_posix()
        for _rows, problems in results:
            for pr in problems:
                print(f"ERROR {rel}: {pr}", file=sys.stderr)
                bad += 1
        if new_text != text:
            stale += 1
            if not check and not any(pr for _r, pr in results):
                path.write_text(new_text, encoding="utf-8")
                print(f"Rewrote diagram in {rel}")
    if check:
        return 1 if (bad or stale) else 0
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
