#!/usr/bin/env python3
"""
Version history of one article, so an article is never edited silently.

Each article under articles/ has a `versions.json` (the data) and a generated
`sections/versions.tex` (the table and the version/status macros the article prints).

Versions are `N.n`. The first draft is `0.1`.
  - The minor number is bumped by Claude on any substantial edit: a claim, a number,
    a source, an equation, a table row, the structure. Typos and formatting are exempt.
  - The major number is bumped only by the user, after a manual review. Major 0 therefore
    means "never reviewed", and the article says so on its title page.

How a silent edit is caught: every row stores a hash of each tracked file (main.tex and
the hand-written sections). `check` compares the files on disk with the last row and names
what changed since. The "sections changed" column is computed from those hashes, not
written by hand.

The printed table stays short. When the major number is bumped, the minor rows of the
previous major collapse into one summary row; row 0.1 and every N.0 review row are always
kept. `versions.json` keeps every row, so nothing is lost; only the printed view is pruned.

Usage (from study/):
    python scripts/article_version.py NAME draft  [--summary TEXT]
    python scripts/article_version.py NAME edit   --summary TEXT [--by WHO]
    python scripts/article_version.py NAME review --summary TEXT [--condensed TEXT]
    python scripts/article_version.py NAME check
    python scripts/article_version.py NAME render

`review` is the user's decision and sits behind a permission prompt.
"""

import argparse
import hashlib
import json
import sys
from datetime import datetime
from pathlib import Path

import _console  # noqa: F401  (UTF-8 console output on Windows)

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_bibliography import ARTICLES_DIR, article_dirs  # noqa: E402
from texutil import tex_escape  # noqa: E402

GENERATED_SECTIONS = {"references.tex", "versions.tex", "comparison_rows.tex"}
VERSIONS_FILE = "versions.json"
TABLE_FILE = Path("sections") / "versions.tex"

TABLE_HEADER = (
    "% GENERATED by study/scripts/article_version.py from versions.json. Do not edit.\n"
)


# ---- reading the article ---------------------------------------------------------------------

def tracked_files(adir):
    """{relative path: sha256 of the text with line endings normalised}: main.tex, the
    hand-written sections and the hand-written figure sources. Generated files are left out."""
    files = {}
    candidates = [adir / "main.tex"]
    candidates += sorted((adir / "sections").glob("*.tex")) if (adir / "sections").exists() else []
    candidates += sorted((adir / "figs").glob("*.tex")) if (adir / "figs").exists() else []
    for path in candidates:
        if path.name in GENERATED_SECTIONS or not path.exists():
            continue
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        files[path.relative_to(adir).as_posix()] = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return files


def changed_between(old, new):
    """Sorted names of the files that differ between two hash maps."""
    return sorted(k for k in set(old) | set(new) if old.get(k) != new.get(k))


def short_name(path):
    name = path[len("sections/"):] if path.startswith("sections/") else path
    return name[:-4] if name.endswith(".tex") else name


# ---- the data file ---------------------------------------------------------------------------

def load(adir):
    path = adir / VERSIONS_FILE
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"rows": []}


def save(adir, data):
    (adir / VERSIONS_FILE).write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def parse_version(v):
    major, minor = v.split(".")
    return int(major), int(minor)


def stamp(now=None):
    return (now or datetime.now()).strftime("%Y-%m-%d %H:%M")


# ---- the operations --------------------------------------------------------------------------

def add_row(adir, kind, summary, by, condensed=None, now=None):
    """Append a row for the article's current files. Returns (row, error)."""
    data = load(adir)
    rows = data["rows"]
    files = tracked_files(adir)
    if kind == "draft":
        if rows:
            return None, "this article already has versions; use edit or review"
        version, changed = "0.1", sorted(files)
    else:
        if not rows:
            return None, "no versions yet; run draft first"
        major, minor = parse_version(rows[-1]["version"])
        changed = changed_between(rows[-1]["files"], files)
        if kind == "edit":
            if not changed:
                return None, f"nothing changed since {rows[-1]['version']}; no new version needed"
            version = f"{major}.{minor + 1}"
        else:
            version = f"{major + 1}.0"
    row = {"version": version, "time": stamp(now), "kind": kind, "by": by,
           "changed": changed, "summary": summary, "files": files}
    if condensed:
        row["condenses"] = condensed
    rows.append(row)
    save(adir, data)
    write_table(adir)
    return row, None


def stale_files(adir):
    """Files changed since the last recorded version, or None if there is no history."""
    rows = load(adir)["rows"]
    if not rows:
        return None
    return changed_between(rows[-1]["files"], tracked_files(adir))


# ---- the printed table -----------------------------------------------------------------------

def display_rows(rows):
    """The rows to print: the open major version in full; each closed major version with its
    minor rows collapsed into one summary row (row 0.1 and every N.0 row stay)."""
    if not rows:
        return []
    latest = parse_version(rows[-1]["version"])[0]
    out = []
    for g in sorted({parse_version(r["version"])[0] for r in rows}):
        group = [r for r in rows if parse_version(r["version"])[0] == g]
        if g == latest:
            out += group
            continue
        keep = [r for r in group if parse_version(r["version"])[1] == 0 or r["version"] == "0.1"]
        fold = [r for r in group if r not in keep]
        if len(fold) < 2:
            out += group
            continue
        successor = next((r for r in rows if parse_version(r["version"]) == (g + 1, 0)), {})
        merged = {
            "version": f"{fold[0]['version']}–{fold[-1]['version']}",
            "time": fold[-1]["time"],
            "kind": "edits",
            "by": " / ".join(sorted({r["by"] for r in fold})),
            "changed": sorted({c for r in fold for c in r["changed"]}),
            "summary": successor.get("condenses") or "; ".join(r["summary"] for r in fold),
        }
        out += sorted(keep + [merged], key=lambda r: parse_version(r["version"].split("–")[0]))
    return out


def status_text(rows):
    """What the title page says about review."""
    reviews = [r for r in rows if r["kind"] == "review"]
    if not reviews:
        return "not reviewed by the user"
    last = reviews[-1]
    text = f"reviewed as v{last['version']} ({last['time'][:10]})"
    if rows[-1] is not last:
        text += ", edited since"
    return text


def render_table(data):
    rows = data["rows"]
    lines = [TABLE_HEADER.rstrip("\n"),
             f"\\newcommand{{\\articleversion}}{{{rows[-1]['version']}}}",
             f"\\newcommand{{\\articlereviewstatus}}{{{tex_escape(status_text(rows))}}}",
             "\\newcommand{\\versiontable}{%",
             "{\\small\\begin{tabularx}{\\linewidth}{@{}l l l L L l@{}}",
             "\\toprule",
             "\\textbf{Version} & \\textbf{Date} & \\textbf{Kind} & \\textbf{Sections changed} & "
             "\\textbf{Summary} & \\textbf{By}\\\\",
             "\\midrule"]
    for r in display_rows(rows):
        sections = ", ".join(short_name(c) for c in r["changed"]) or "none"
        lines.append(" & ".join([tex_escape(r["version"]), tex_escape(r["time"]), tex_escape(r["kind"]),
                                 tex_escape(sections), tex_escape(r["summary"]), tex_escape(r["by"])]) + "\\\\")
    lines += ["\\bottomrule", "\\end{tabularx}}}", ""]
    return "\n".join(lines)


def write_table(adir):
    """Regenerate sections/versions.tex. Returns True if it changed."""
    data = load(adir)
    if not data["rows"]:
        return False
    text = render_table(data)
    path = adir / TABLE_FILE
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    if text == old:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


# ---- command line ----------------------------------------------------------------------------

def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("name", help="article folder name under articles/")
    p.add_argument("command", choices=["draft", "edit", "review", "check", "render"])
    p.add_argument("--summary", default="")
    p.add_argument("--by", default="")
    p.add_argument("--condensed", default="", help="review only: one summary for the minor rows it folds")
    args = p.parse_args(argv)

    adir = ARTICLES_DIR / args.name
    if adir not in article_dirs():
        print(f"No article named '{args.name}' under articles/.", file=sys.stderr)
        return 1
    if args.command == "render":
        print("versions.tex rewritten." if write_table(adir) else "versions.tex already up to date.")
        return 0
    if args.command == "check":
        stale = stale_files(adir)
        if stale is None:
            print(f"{args.name}: no version history yet (run draft).")
            return 1
        if stale:
            print(f"{args.name}: changed since the last version: {', '.join(short_name(s) for s in stale)}")
            return 1
        print(f"{args.name}: matches version {load(adir)['rows'][-1]['version']}.")
        return 0

    if args.command in ("edit", "review") and not args.summary:
        print("--summary is required.", file=sys.stderr)
        return 1
    summary = args.summary or "First draft"
    by = args.by or ("User" if args.command == "review" else "Claude")
    row, error = add_row(adir, args.command, summary, by, args.condensed or None)
    if error:
        print(f"{args.name}: {error}", file=sys.stderr)
        return 1
    print(f"{args.name}: version {row['version']} recorded ({len(row['changed'])} file(s) changed).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
