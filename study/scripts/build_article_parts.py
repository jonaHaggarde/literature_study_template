#!/usr/bin/env python3
"""
Regenerates the parts of an article that are computed from data, so they cannot drift from it.

  map           sections/coverage_table.tex     sources per method family, from the method cards
  requirements  sections/traceability_table.tex each requirement's path up to the primary ones,
                                                 with the gaps flagged, from the P- and D- tables
  rationale     sections/decision_tree.tex      the decision tree, from decision_tree.md

Each hand-written section `\\input`s its generated file, so the explanation stays hand-written
and the numbers and the picture are never typed. Generated files are not tracked by the version
history (they follow from what is); `decision_tree.md` is the data and is tracked.

Usage (from study/):
    python scripts/build_article_parts.py NAME [--check]
"""

import re
import sys
from pathlib import Path

import _console  # noqa: F401  (UTF-8 console output on Windows)

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_bibliography import ARTICLES_DIR  # noqa: E402
from texutil import tex_escape as esc  # noqa: E402

HEADER = ("% GENERATED by study/scripts/build_article_parts.py from {source}.\n"
          "% Never edit this file; change the data and rebuild.\n")
ID_RE = re.compile(r"^[PD]-\d+$")
PARENT_RE = re.compile(r"[PD]-\d+")
ASSUMED_RE = re.compile(r"\bassum", re.I)
TBD_RE = re.compile(r"\bTB[DR]\b")


def flag(text):
    return f"\\textcolor{{red!60!black}}{{{esc(text)}}}"


# ---- requirements traceability ---------------------------------------------------------------

def table_rows(tex):
    """The rows of a requirements table: lists of cell strings, for lines that start with an ID.
    A row still holding a \\todo placeholder is not a requirement yet."""
    rows = []
    for line in tex.splitlines():
        cells = [c.strip() for c in line.rstrip().rstrip("\\").rstrip().split("&")]
        if len(cells) > 1 and ID_RE.match(cells[0]) and not any("\\todo" in c for c in cells):
            rows.append(cells)
    return rows


def parents_of(cell):
    return PARENT_RE.findall(cell)


def ancestors(rid, parents, seen=None):
    """All requirements reachable by following parents."""
    seen = set() if seen is None else seen
    for p in parents.get(rid, []):
        if p not in seen:
            seen.add(p)
            ancestors(p, parents, seen)
    return seen


def traceability(primary_tex, derived_tex):
    """(derived_rows, primary_rows, problems) for the generated tables. Each row is a list of
    cells; problems are readable strings."""
    primary = table_rows(primary_tex)
    derived = table_rows(derived_tex)
    primary_ids = {r[0] for r in primary}
    derived_ids = {r[0] for r in derived}
    parents = {r[0]: parents_of(r[2]) for r in derived if len(r) > 2}
    children = {}
    out_derived, out_primary, problems = [], [], []
    for r in derived:
        rid = r[0]
        ps = parents.get(rid, [])
        notes = []
        if not ps:
            notes.append("no parent")
        unknown = [p for p in ps if p not in primary_ids | derived_ids]
        if unknown:
            notes.append("unknown parent " + ", ".join(unknown))
        reach = ancestors(rid, parents)
        cycle = rid in reach
        if cycle:
            notes.append("cycle")
        tops = sorted(a for a in reach if a in primary_ids)
        if ps and not tops and not cycle:
            notes.append("no path to a primary requirement")
        for p in ps:
            children.setdefault(p, []).append(rid)
        out_derived.append((rid, r[1] if len(r) > 1 else "", ", ".join(ps), ", ".join(tops), notes))
        problems += [f"{rid}: {n}" for n in notes]
    for r in primary:
        rid = r[0]
        param = r[1] if len(r) > 1 else ""
        value = r[2] if len(r) > 2 else ""
        source = r[5] if len(r) > 5 else ""
        notes = []
        if not source:
            notes.append("no source")
        elif ASSUMED_RE.search(source):
            notes.append("source is an assumption")
        if TBD_RE.search(value) or not value:
            notes.append("value TBD")
        used = sorted({c for c in children.get(rid, [])})
        out_primary.append((rid, param, source, ", ".join(used), notes))
        problems += [f"{rid}: {n}" for n in notes if n != "value TBD"]
    return out_derived, out_primary, problems


def render_traceability(primary_tex, derived_tex):
    derived, primary, _ = traceability(primary_tex, derived_tex)
    out = [HEADER.format(source="the tables in sections/primary.tex and sections/derived.tex").rstrip("\n")]
    if not derived and not primary:
        out += ["\\noindent\\emph{No requirements recorded yet; the traceability tables appear here once the "
                "primary and derived tables have rows.}", ""]
        return "\n".join(out)

    def cell_flags(notes):
        return "; ".join(flag(n) for n in notes) if notes else "ok"

    out += ["\\noindent\\textbf{Primary requirements}", "\\smallskip", "",
            "\\noindent\\begin{tabularx}{\\linewidth}{@{}l L L L L@{}}", "\\toprule",
            "\\textbf{ID} & \\textbf{Parameter} & \\textbf{Source} & \\textbf{Used by} & \\textbf{Check}\\\\", "\\midrule"]
    for rid, param, source, used, notes in primary:
        out.append(f"{esc(rid)} & {esc(param)} & {esc(source) or '--'} & {esc(used) or '--'} & {cell_flags(notes)}\\\\")
    out += ["\\bottomrule", "\\end{tabularx}", "", "\\bigskip", "",
            "\\noindent\\textbf{Derived requirements}", "\\smallskip", "",
            "\\noindent\\begin{tabularx}{\\linewidth}{@{}l L l l L@{}}", "\\toprule",
            "\\textbf{ID} & \\textbf{Requirement} & \\textbf{Parents} & \\textbf{Primary ancestors} & "
            "\\textbf{Check}\\\\", "\\midrule"]
    for rid, req, ps, tops, notes in derived:
        out.append(f"{esc(rid)} & {esc(req)} & {esc(ps) or '--'} & {esc(tops) or '--'} & {cell_flags(notes)}\\\\")
    out += ["\\bottomrule", "\\end{tabularx}", ""]
    return "\n".join(out)


# ---- map coverage ----------------------------------------------------------------------------

def coverage_counts(cards):
    """{family: (sources, cards)} from (entry_id, family) pairs, one pair per method card."""
    sources, counts = {}, {}
    for entry_id, family in cards:
        sources.setdefault(family, set()).add(entry_id)
        counts[family] = counts.get(family, 0) + 1
    return {f: (len(sources[f]), counts[f]) for f in sources}


def render_coverage(cards, canonical=()):
    counts = coverage_counts(cards)
    out = [HEADER.format(source="the method cards in study/notes/ and the families in study/topics/families.md")
           .rstrip("\n")]
    if not counts:
        out += ["\\noindent\\emph{No method cards yet; the counts appear here once notes have method cards.}", ""]
        return "\n".join(out)
    total = len({e for e, _ in cards})
    order = [f for f in canonical if f in counts] + sorted(f for f in counts if f and f not in canonical)
    if "" in counts:
        order.append("")
    out += ["\\noindent\\begin{tabularx}{\\linewidth}{@{}L r r r@{}}", "\\toprule",
            "\\textbf{Family} & \\textbf{Sources} & \\textbf{Cards} & \\textbf{Share of sources}\\\\", "\\midrule"]
    for fam in order:
        n, c = counts[fam]
        share = f"{100 * n / total:.0f}\\%"
        label = esc(fam) if fam else "\\emph{no family}"
        out.append(f"{label} & {n} & {c} & {share}\\\\")
    out += ["\\midrule", f"\\textbf{{Distinct sources}} & {total} & {len(cards)} & \\\\",
            "\\bottomrule", "\\end{tabularx}", "",
            "\\noindent\\footnotesize A source with cards in several families counts once in each, so the "
            "shares can add up to more than 100\\%.", ""]
    return "\n".join(out)


def map_cards():
    """(entry_id, family) for every method card in the study."""
    from build_catalog_index import CATALOG_PATH, parse_catalog
    from method_cards import FAMILY_KEY, iter_cards
    entries = parse_catalog(CATALOG_PATH.read_text(encoding="utf-8")) if CATALOG_PATH.exists() else []
    return [(entry_id, values.get(FAMILY_KEY, "")) for entry_id, _f, _n, _name, values, _k in iter_cards(entries)]


# ---- the generation --------------------------------------------------------------------------

def write_if_changed(path, text, check=False):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return True


def build(name, articles_dir=ARTICLES_DIR, check=False, cards=None):
    """Regenerate the article's computed parts. Returns (changed_files, problems)."""
    adir = articles_dir / name
    changed, problems = [], []
    if name == "requirements":
        read = lambda f: (adir / "sections" / f).read_text(encoding="utf-8") if (adir / "sections" / f).exists() else ""
        text = render_traceability(read("primary.tex"), read("derived.tex"))
        if write_if_changed(adir / "sections" / "traceability_table.tex", text, check):
            changed.append("traceability_table.tex")
    elif name == "map":
        from method_cards import load_families
        text = render_coverage(map_cards() if cards is None else cards, load_families())
        if write_if_changed(adir / "sections" / "coverage_table.tex", text, check):
            changed.append("coverage_table.tex")
    elif name == "rationale":
        import build_decision_trees as bdt
        import tree_latex
        source = adir / "decision_tree.md"
        if source.exists():
            m = bdt.TABLE_RE.search(source.read_text(encoding="utf-8"))
            if not m:
                problems.append("decision_tree.md has no <!-- decision-tree --> table")
            else:
                rows, problems = bdt.parse_table(m.group(2))
                problems = problems or bdt.validate(rows)
                if not problems:
                    text = HEADER.format(source="decision_tree.md") + tree_latex.render_latex(rows)
                    if write_if_changed(adir / "sections" / "decision_tree.tex", text, check):
                        changed.append("decision_tree.tex")
    return changed, problems


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    check = "--check" in argv
    names = [a for a in argv if not a.startswith("--")]
    if not names:
        print(__doc__)
        return 0
    changed, problems = build(names[0], check=check)
    for p in problems:
        print(f"{names[0]}: {p}", file=sys.stderr)
    if check and changed:
        print(f"{names[0]}: stale generated file(s): {', '.join(changed)}", file=sys.stderr)
    return 1 if problems or (check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
